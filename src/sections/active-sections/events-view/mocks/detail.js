export function getEventDetail(id) {
  const event = EVENTS.find((item) => item.id === String(id));
  if (!event) return null;

  const extra = DETAILS[event.id] || {};

  return {
    ...event,
    ...extra,
    attendeesList: extra.attendees || [],
    reports: extra.reports || [],
    activity: extra.activity || [],
    rsvp: extra.rsvp || { going: 0, pending: 0, waitlist: 0, cancelled: 0 },
    visibilityList: extra.visibilityList || { shown: 0, hidden: 0 },
  };
}
